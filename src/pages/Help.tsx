function SectionContent({ items }: { items: ContentItem[] }) {
  return (
    <Box>
      {items.map((item, i) => {
        if (item.type === 'subheading') {
          return (
            <Typography
              key={i}
              variant="subtitle2"
              fontWeight={700}
              sx={{ mt: i === 0 ? 0 : 2, mb: 0.5, color: 'text.primary' }}
            >
              {item.text}
            </Typography>
          )
        }

        if (item.type === 'note') {
          return (
            <Box
              key={i}
              sx={{
                display: 'flex',
                alignItems: 'flex-start',
                gap: 1,
                mt: 1.5,
                p: 1.5,
                bgcolor: 'action.hover',
                borderRadius: 1,
                borderRight: '3px solid',
                borderColor: 'info.main',
              }}
            >
              <TipIcon fontSize="small" color="info" sx={{ mt: '2px', flexShrink: 0 }} />
              <Typography variant="body2" color="text.secondary">
                {item.text}
              </Typography>
            </Box>
          )
        }

        if (item.type === 'step') {
          const stepNumber =
            items.slice(0, i).filter((x) => x.type === 'step').length + 1
          return (
            <Box
              key={i}
              sx={{ display: 'flex', alignItems: 'flex-start', gap: 1.5, mt: 0.75 }}
            >
              <Chip
                label={stepNumber}
                size="small"
                color="primary"
                sx={{ height: 20, minWidth: 20, fontSize: '0.7rem', flexShrink: 0, mt: '2px' }}
              />
              <Typography variant="body2">{item.text}</Typography>
            </Box>
          )
        }

        // type === 'text'
        return (
          <Box
            key={i}
            sx={{ display: 'flex', alignItems: 'flex-start', gap: 1, mt: 0.75 }}
          >
            <CheckIcon color="success" fontSize="small" sx={{ mt: '2px', flexShrink: 0 }} />
            <Typography variant="body2">{item.text}</Typography>
          </Box>
        )
      })}
    </Box>
  )
}

